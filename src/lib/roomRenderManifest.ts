export function applyRoomRenderMedia(asset: ArchitecturalAsset): ArchitecturalAsset {
  if (!VERIFIED_ROOM_RENDER_IDS.has(asset.id)) {
    return asset;
  }

  return {
    ...asset,
    roomRenderUrl: `/assets/room-renders/${asset.id}.jpg`,
    hoverCutoutUrl: PURE_WHITE_HOVER_CUTOUT_IDS.has(asset.id)
      ? `/assets/cutouts/${asset.id}.png`
      : asset.hoverCutoutUrl,
  };
}
