import type {
  ArchitecturalAsset,
  AssetCategory,
  MaterialFinish,
  PlacementType,
} from './catalogTypes';
import { ARCHITECTURAL_PBR_PATTERNS } from './expandedInteriorAssets';

type SourceSpec =
  | { kind: 'ph'; id: string }
  | { kind: 'obj'; id: string }
  | { kind: 'sim'; id: string };

interface CompactReadyMadeSeed {
  id: string;
  slug: string;
  name: string;
  brandStyle: string;
  category: AssetCategory;
  placement?: PlacementType;
  dims: [number, number, number, number?]; // [w, d, h, mountHeight?]
  poly: number;
  mat: MaterialFinish['materialKind'];
  colors: [string, string, string];
  surface: string;
  kw: string[];
  rooms: string[];
  summary: string;
  src: SourceSpec;
}

function buildReadyMadeAsset(s: CompactReadyMadeSeed): ArchitecturalAsset {
  const [width, depth, height, mountHeight] = s.dims;
  const isPh = s.src.kind === 'ph';
  const repo = s.src.kind === 'sim' ? 'simready-glb' : 'objaverse-clean-glb';
  const gltfUrl = isPh
    ? `/api/v1/polyhaven/${s.src.id}/model.gltf`
    : `/api/v1/hf/glb/${repo}/${s.src.id}`;
  const thumbnailUrl = isPh
    ? `https://cdn.polyhaven.com/asset_img/primary/${s.src.id}.png?height=512`
    : `https://huggingface.co/datasets/codepawl/${repo}/resolve/main/thumbs/${s.src.id}.webp`;
  const sourcePageUrl = isPh
    ? `https://polyhaven.com/a/${s.src.id}`
    : `https://huggingface.co/datasets/codepawl/${repo}`;
  const roughness = s.mat === 'fabric' ? 0.85 : s.mat === 'metal' ? 0.34 : s.mat === 'ceramic' ? 0.36 : 0.5;
  const metalness = s.mat === 'metal' ? 0.52 : 0.04;

  return {
    id: s.id,
    slug: s.slug,
    name: s.name,
    brandStyle: s.brandStyle,
    category: s.category,
    archetype: 'external_gltf',
    placement: s.placement ?? 'floor',
    dimensionsCm: mountHeight ? { width, depth, height, mountHeight } : { width, depth, height },
    polyEstimate: s.poly,
    renderEngines: ['Cycles', 'EEVEE', 'Unreal Engine 5'],
    uvUnwrapped: true,
    thumbnailUrl,
    searchKeywords: s.kw,
    roomTags: s.rooms,
    aiSummary: s.summary,
    finishes: [
      {
        id: 'orijinal-pbr',
        label: 'Orijinal PBR',
        materialKind: s.mat,
        primaryHex: s.colors[0],
        secondaryHex: s.colors[1],
        accentHex: s.colors[2],
        roughness,
        metalness,
        preserveOriginalTextures: true,
      },
    ],
    defaultFinishId: 'orijinal-pbr',
    patterns: ARCHITECTURAL_PBR_PATTERNS,
    defaultPatternId: 'original_pbr',
    modelingSpec: {
      geometryBreakdown: [
        `Dış ölçüler: ${width}×${depth}×${height} cm (1:1 metrik ölçekli hazır 3D mesh, zemin Z=0 oturtmalı).`,
        `${s.name} için optimize edilmiş çok parçalı UV haritalı hazır PBR 3D geometri.`,
        'Blender 4.x glTF/GLB içe aktarıcı ile gömülü PBR dokularla doğrudan sahneye yerleşir.',
      ],
      textureAndMaps: {
        surfaceType: s.surface,
        uvTileCm: 'Orijinal Unwrapped UV (BaseColor + Normal + Roughness/Metallic)',
        bumpDepthMm: '0.4 – 2.0 mm PBR Mikro Yüzey Kabartması',
        roughnessRange: `${Math.max(0.08, roughness - 0.14).toFixed(2)} – ${Math.min(0.95, roughness + 0.1).toFixed(2)}`,
        shaderRecipe:
          'Principled BSDF gömülü PBR dokular + MimarKatalog çok parçalı Türkiye mağaza renk kombinasyonu desteği.',
      },
      microDetails: [
        `${s.brandStyle} koleksiyonuna uygun gerçekçi ev içi detay oranları.`,
        'Blender Asset Browser (col.asset_mark()) ve tek tıkla GLB indirme uyumlu.',
      ],
      blenderModifiers: ['Weighted Normal (Keep Sharp)', 'Smooth by Angle (30°)'],
      lightingAndCameraTip:
        'Doğal pencere gün ışığı ve sıcak iç mekan vurgusuyla ev içi yaşam hissini güçlendirin.',
      aiRenderPrompt: `Photorealistic interior architectural photography of ${s.name} (${width}x${depth}x${height} cm), ${s.surface}, placed naturally in a contemporary Turkish home interior, Cycles 8k.`,
      aiBlenderMasterPrompt: `Import ${s.name} (${width}x${depth}x${height} cm) at 1:1 metric scale with Z=0 floor grounding and preserve PBR maps or apply selected Turkish retail finish.`,
    },
    modelSource: {
      provider: isPh ? 'polyhaven' : 'hf',
      ...(isPh ? { polyhavenId: s.src.id } : {}),
      gltfUrl,
      license: isPh ? 'CC0 (Ticari Kullanım Serbest)' : 'CC-BY / Açık Mimari GLB',
    },
    sourceOrigin: 'catalog',
  };
}

