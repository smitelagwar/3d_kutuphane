export function isRugAsset(asset: ArchitecturalAsset): boolean {
  if (asset.archetype === 'modern_rug') return true;
  if (/havlu|bornoz|towel/i.test(asset.name)) return false;
  return /halı|hali|kilim|yolluk|yolluğ|yollug|paspas|\brug\b|carpet/i.test(asset.name);
}

export const INITIAL_TURKISH_ASSETS: ArchitecturalAsset[] = BASE_TURKISH_ASSETS
  .filter((rawAsset) => !NON_TURKISH_PRUNED_IDS.has(rawAsset.id))
  .map((rawAsset) => {
  // 1. Full Turkish retail market localization: category fixes, Turkish metric dimensions,
  //    clean Turkish product names, and verified Turkish brand/series/retail channel metadata
  const asset = applyRoomRenderMedia(applyTurkishMarketLocalization(rawAsset));

  const withPatterns =
    asset.archetype === 'external_gltf' && asset.defaultPatternId === 'original_pbr'
      ? { ...asset, patterns: ARCHITECTURAL_PBR_PATTERNS }
      : asset;

  const isRug = isRugAsset(withPatterns);

  if (isRug) {
    if (withPatterns.archetype === 'modern_rug') {
      return {
        ...withPatterns,
        finishes: PROCEDURAL_RUG_DESIGNER_FINISHES,
        defaultFinishId: PROCEDURAL_RUG_DESIGNER_FINISHES[0].id,
      };
    }

    return {
      ...withPatterns,
      finishes: CURATED_RUG_DESIGNER_FINISHES,
      defaultFinishId: CURATED_RUG_DESIGNER_FINISHES[0].id,
    };
  }

  // Phase 1 + Phase 2 real-world retail multi-part color combinations (all 750/750 catalog assets)
  const retailFinishes = getRetailFinishesForAsset(withPatterns, false);
  if (retailFinishes && retailFinishes.length > 0) {
    return {
      ...withPatterns,
      finishes: retailFinishes,
      defaultFinishId: retailFinishes[0].id,
    };
  }

  return withPatterns;
});

