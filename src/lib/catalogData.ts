      name: def.name,
      brandStyle: def.brandStyle,
      category: def.category,
      dimensionsCm: def.dimensionsCm,
      primaryHex: def.primaryHex,
      surfaceType: def.surfaceType,
      providerLabel: `Poly Haven CC0 (${def.phId})`,
